# AO* Algorithm

graph = {
    'A': [['B', 'C'], ['D']],
    'B': [['E']],
    'C': [['F']],
    'D': [],
    'E': [],
    'F': []
}

cost = {
    'A': 1, 'B': 2, 'C': 3,
    'D': 4, 'E': 5, 'F': 6
}

def ao_star(node):
    if node not in graph or not graph[node]:
        return cost[node]

    best = float('inf')

    for path in graph[node]:
        total = 0
        for child in path:
            total += ao_star(child)
        best = min(best, total)

    cost[node] = best
    return best

print("Minimum Cost:", ao_star('A'))